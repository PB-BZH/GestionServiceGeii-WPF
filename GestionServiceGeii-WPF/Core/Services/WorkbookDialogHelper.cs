using GestionServiceGeii.Core.Enums;

namespace GestionServiceGeii.Core.Services {
  internal class WorkbookDialogHelper {
    internal static string GetWorkbookDialogTitle(WorkbookRole role) {
      return role switch {
        WorkbookRole.Selection => "FICHIER DE SELECTION",
        WorkbookRole.Service => "FICHIER DE SERVICE",
        _ => throw new InvalidOperationException("Rôle de fichier ExcelApp inconnu : " + role),
      };
    }
  }
}
